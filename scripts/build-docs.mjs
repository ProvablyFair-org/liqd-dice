#!/usr/bin/env node
/**
 * build-docs.mjs — the three companion documents, generated.
 *
 *   node scripts/build-docs.mjs           write evidence.md, exploit-testing.md, SUMMARY.md
 *   node scripts/build-docs.mjs --check   exit 1 if a committed one differs from what is generated
 *
 * ONE SOURCE PER FACT. The evidence rows, the S5 matrix, the supplementary row and the result of the
 * last full mutation run are READ from MANIFEST.md; the registry tables are read from
 * tests/mutations.json, tests/structural-forgeries.json and tests/mutation-survivors.json; every
 * SHA-256 is computed from the file on disk; the table of contents is the headings of README.md and
 * MANIFEST.md. Nothing measurable is typed here. tests/dice/docsTests.ts runs the check, so a
 * companion document cannot drift from the overview.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const sha = (rel) => createHash('sha256').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex');
const manifest = read('MANIFEST.md');
const need = (v, what) => { if (v === null || v === undefined || v === -1) throw new Error(`build-docs: ${what} not found in MANIFEST.md`); return v; };
const header = (m) => { const h = need(/^\*\*Audit ID:\*\*.*$/m.exec(manifest), 'identity line')[0]; return h; };

// Where each evidence item comes from. Keyed by the id the MANIFEST register uses.
const ORIGIN = {
  E01: 'converted by the auditor from the capture runner\'s four raw exports of 7 and 10 November 2026 (liqd.com); every served value kept as served',
  E02: 'written by `npm run report` from E01 and E03',
  E03: 'written by `npm run simulate` from the pinned master seed and the revealed seeds of E01',
  E04: 'written by `npm run simulate` from the 98-target series of E03',
  E05: 'auditor code and specification; the specification\'s counts are reprinted by `scripts/algorithm-spec-check.mjs`',
  E06: 'auditor code', E07: 'auditor code', E08: 'auditor code', E09: 'auditor code',
  E15: 'written by `npm run report` from E01',
  E16: 'printed by the auditor\'s capture checker from the raw export of 7 November 2026',
  E17: 'LIQD\'s production verify endpoint, called logged out by the auditor on 9 November 2026; built from the raw call log',
  E18: 'printed by the auditor\'s capture checker from the first raw export of 10 November 2026',
  E19: 'printed by the auditor\'s capture checker from the second raw export of 10 November 2026',
  E20: 'LIQD\'s production verify endpoint, called logged out by the auditor on 10 November 2026; built from the raw call log',
  E21: 'printed by the auditor\'s capture checker from the third raw export of 10 November 2026',
  '—': 'read by the auditor from the live liqd.com pages, logged out, on 1 October 2026',
};

// ── evidence.md ─────────────────────────────────────────────────────────────
function evidenceDoc() {
  const start = need(manifest.indexOf('\n## Evidence\n'), 'Evidence section');
  const sect = manifest.slice(start, manifest.indexOf('\n## ', start + 5));
  const rows = sect.split('\n').filter((l) => /^\| (E\d{2}|—) \|/.test(l));
  if (rows.length < 10) throw new Error('build-docs: evidence register rows not found');
  const out = rows.map((l) => {
    const cells = l.split('|').slice(1, -1).map((c) => c.trim());
    const [id, fileCell, ...rest] = cells; const role = rest.join(' | ');
    const files = [...fileCell.matchAll(/\]\(([^)]+)\)/g)].map((m) => m[1]);
    let hash;
    if (files.length) hash = files.map((f) => `\`${sha(f)}\`${files.length > 1 ? ` (${f})` : ''}`).join('<br>');
    else {
      // a file pattern (the unit tests): one digest over the sorted per-file digests
      const dir = 'tests/dice'; const list = fs.readdirSync(path.join(ROOT, dir)).filter((f) => f.endsWith('Tests.ts')).sort();
      hash = `\`${createHash('sha256').update(list.map((f) => sha(`${dir}/${f}`)).join('\n')).digest('hex')}\` (SHA-256 over the sorted SHA-256 of the ${list.length} files)`;
    }
    if (!ORIGIN[id]) throw new Error(`build-docs: no origin recorded for evidence item ${id}`);
    return `| ${id} | ${fileCell} | ${role} | ${ORIGIN[id]} | ${hash} |`;
  });
  return `# LIQD Dice — Evidence register\n\n${header()}\n\n`
    + 'Generated by `node scripts/build-docs.mjs` from the evidence table of [MANIFEST.md](MANIFEST.md#evidence) and the files on disk; `tests/dice/docsTests.ts` fails if this file differs from what the generator writes. Each item is listed with what it is, where it came from and the SHA-256 of the file as shipped. Items E01 to E09 and E15 are the data, the code and the results; E16 to E19 are records of the production captures and of LIQD\'s production verifier. Numbers E10 to E14 are not used.\n\n'
    + '| ID | File | What it is and its role | Origin | SHA-256 |\n|---|---|---|---|---|\n' + out.join('\n') + '\n';
}

// ── exploit-testing.md ──────────────────────────────────────────────────────
function exploitDoc() {
  const a = need(manifest.indexOf('<!-- S5-MATRIX:START -->'), 'S5 matrix start'), b = need(manifest.indexOf('<!-- S5-MATRIX:END -->'), 'S5 matrix end');
  const matrix = manifest.slice(a + '<!-- S5-MATRIX:START -->'.length, b).trim();
  const after = manifest.slice(b, manifest.indexOf('\n## ', b));
  const supp = after.split('\n').filter((l) => /^\| (Supplementary|---|S5-D\d)/.test(l)).join('\n');
  const run = need(/Mutation run of record: `npm run mutate`, ([^:]+): \*\*([^*]+)\*\*/.exec(manifest), 'mutation run of record');
  const muts = JSON.parse(read('tests/mutations.json')), forg = JSON.parse(read('tests/structural-forgeries.json')), surv = JSON.parse(read('tests/mutation-survivors.json'));
  const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
  // An entry about the rejection guard tests the AUDIT module; the operator's guard is a declared assumption.
  const named = (m) => cell(m.name) + (/rejection guard/i.test(m.name) ? ' (the audit module\'s own guard; that the operator applies one is ASSUMED, **L11**)' : '');
  const stepOf = (m) => (m.expect && /Step \d+/.test(m.expect) && !/^NOT/.test(m.expect) ? m.expect : (m.runner === 'mocha' ? 'the unit suite fails' : `[FAIL] ${(/Step\s+\d+/.exec(m.guard) || ['a named step'])[0]}`));
  const mRows = muts.map((m, i) => `| M${String(i).padStart(2, '0')} | ${named(m)} | \`${m.file}\` | ${cell(stepOf(m))} |`);
  const fRows = forg.map((m, i) => `| M${String(muts.length + i).padStart(2, '0')} | ${named(m)} | \`${m.script}\` | ${cell(stepOf(m))} |`);
  const info = muts.filter((m) => /^\[INFO\]/.test(m.expect || '')).length, over = muts.filter((m) => /OVERSTATED/.test(m.expect || '')).length;
  return `# LIQD Dice — Integrity, forgery and mutation testing\n\n${header()}\n\n`
    + 'Generated by `node scripts/build-docs.mjs` from the integrity-check matrix of [MANIFEST.md](MANIFEST.md#integrity-matrix) and the registries under `tests/`; `tests/dice/docsTests.ts` fails if this file differs from what the generator writes.\n\n'
    + '## Fairness-integrity matrix (S5)\n\n' + matrix + '\n\n' + supp + '\n\n'
    + 'S5: fairness-integrity matrix. This page covers the package\'s offline checks; live-API integrity testing is in Section 5 of the report.\n\n'
    + '## Mutation and forgery battery\n\n'
    + `\`npm run mutate\` applies every entry below in a sandbox copy and requires the named step to fire. The registry holds ${muts.length} find/replace mutations, ${forg.length} forgery scripts and ${surv.length} declared survivors: ${muts.length + forg.length + surv.length} entries. ${info} of the mutations is aimed at the informational Step 22 and is recorded as an informational signal, not a kill; ${over} must end RTP FIGURE OVERSTATED after the table and record are regenerated.\n\n`
    + `**Run of record** (${run[1]}): ${run[2]}.\n\n`
    + 'This release differs from the tree the run of record ran on only in comments, document and printed wording, `package.json` `engines` (`>=22.23.1 <23`) and `.nvmrc` (22.23.1) with the unit test that holds them to the validated runtime, one plan note in the dataset header where a name was replaced by "the auditor" (`DATASET_SHA256` re-pinned to the new bytes), the pattern `scripts/build-docs.mjs` uses to read this run from MANIFEST.md, and the files regenerated from these (`outputs/verification-results.json`, `outputs/report-figures.json`, the three companion documents, `verify.js`, `test.js` and `RELEASE-MANIFEST.json`); the battery was not rerun on this release.\n\n'
    + '### Find/replace mutations\n\n| # | Mutation | File | Must end with |\n|---|---|---|---|\n' + mRows.join('\n') + '\n\n'
    + '### Forgery scripts (each re-pins the hash it invalidates)\n\n| # | Forgery | Script | Must end with |\n|---|---|---|---|\n' + fRows.join('\n') + '\n\n'
    + `### Declared survivors\n\n${surv.length === 0 ? 'None.' : surv.map((m) => `- ${m.name}`).join('\n')}\n`;
}

// ── SUMMARY.md ──────────────────────────────────────────────────────────────
function summaryDoc() {
  const slug = (h) => h.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-');
  const heads = (rel, depth) => read(rel).split('\n').filter((l) => new RegExp(`^#{2,${depth}} `).test(l))
    .map((l) => { const lvl = l.indexOf(' '); const t = l.slice(lvl + 1).trim(); return `${'  '.repeat(lvl - 1)}* [${t}](${rel}#${slug(t)})`; });
  return '# Summary\n\n'
    + '* [LIQD Dice — Provably Fair Audit](README.md)\n' + heads('README.md', 2).join('\n') + '\n'
    + '* [Consolidated audit overview](MANIFEST.md)\n' + heads('MANIFEST.md', 3).join('\n') + '\n'
    + '* [Evidence register](evidence.md)\n* [Integrity, forgery and mutation testing](exploit-testing.md)\n* [Algorithm specification](docs/ALGORITHM.md)\n* [Module interface](docs/INTERFACE.md)\n';
}

const docs = { 'evidence.md': evidenceDoc(), 'exploit-testing.md': exploitDoc(), 'SUMMARY.md': summaryDoc() };
let drift = 0;
for (const [name, text] of Object.entries(docs)) {
  const p = path.join(ROOT, name);
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(p) && fs.readFileSync(p, 'utf8') === text;
    console.log(`[build-docs] ${name} ${same ? 'is what the generator writes' : 'DIFFERS from what the generator writes: run node scripts/build-docs.mjs'}`);
    if (!same) drift = 1;
  } else { fs.writeFileSync(p, text); console.log(`[build-docs] wrote ${name} (${text.length} bytes)`); }
}
process.exit(drift);
